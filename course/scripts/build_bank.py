#!/usr/bin/env python3
"""Merge every day's items.json into output/bank.js.

Why this exists: a practice page only embeds its own day's questions, so the
review queue — which spans every day you have ever answered — had nothing to
ask from. The bank is one file, loaded by every page and cached by the browser
after the first hit, holding every reviewable item across all built days.

Audio paths are rewritten from day-relative (`audio/x.mp3`) to page-relative
(`../day03/audio/x.mp3`), because a Day 21 page asking a Day 03 question has to
reach across directories to play it.

Run after build_trr.py:
    .venv/bin/python scripts/build_bank.py
"""
import json, os, glob, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WEB = os.path.join(ROOT, 'output')
OUT = os.path.join(WEB, 'bank.js')

AUDIO_KEYS = ('audio', 'exAudio', 'chunkAudio')


def prep(item, day):
    """Point audio at the day that owns the file, and namespace the review key.

    Chunk ids restart at 01 every day, so a bare cid collides across days —
    Day 03's chunk 01 would inherit Day 01's schedule. The day prefix is what
    makes the key identify one thing you learned on one day."""
    q = item['q']
    for k in AUDIO_KEYS:
        v = q.get(k)
        if isinstance(v, str) and v.startswith('audio/'):
            q[k] = f'../day{day:02d}/{v}'
    item['key'] = f"day{day:02d}:{q['cid']}"
    item['day'] = day
    return item


bank, total = {}, 0
for path in sorted(glob.glob(os.path.join(WEB, 'day*', 'items.json'))):
    d = json.load(open(path, encoding='utf-8'))
    day = d['day']
    bank[str(day)] = {
        'day': day, 'theme': d.get('theme', ''), 'icon': d.get('icon', '📘'),
        'items': [prep(i, day) for i in d['items']],
    }
    total += len(d['items'])

if not bank:
    raise SystemExit('no items.json found — run build_trr.py first')

with open(OUT, 'w', encoding='utf-8') as f:
    f.write('/* Generated by build_bank.py — every reviewable item, all days. */\n')
    f.write('window.TOEIC_BANK = ')
    json.dump(bank, f, ensure_ascii=False, separators=(',', ':'))
    f.write(';\n')

keys = {i['key'] for d in bank.values() for i in d['items']}
print(f'✓ {OUT}')
print(f'  days       : {len(bank)}  ({", ".join(sorted(bank, key=int))})')
print(f'  items      : {total}')
print(f'  review keys: {len(keys)}')
print(f'  size       : {os.path.getsize(OUT)/1024:.0f} KB')
