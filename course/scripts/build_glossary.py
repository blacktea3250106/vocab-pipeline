#!/usr/bin/env python3
"""
Build output/glossary.js — every word the course teaches, with its Chinese.

The Word Vault stores what you tapped plus the sentence it came from, so its
cards could only ever show a *sentence* translation. This gives it the gloss
for the word itself, and it comes from the course's own data rather than an
outside dictionary: whatever the book says a word means is what the card says.

Emits a flat entry list plus a word→entries index, so tapping any single word
in a passage can find the phrase it belongs to (`entitled` → `be entitled to`).
"""
import json, re, sys, unicodedata
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
OUT = ROOT / "output" / "glossary.js"

# indexing these would point half the vocabulary at the same entry
STOP = {"a", "an", "the", "to", "of", "in", "for", "with", "on", "at", "be", "is",
        "are", "was", "were", "do", "does", "did", "and", "or", "but", "one's",
        "oneself", "someone", "something", "sb", "sth", "ing", "your", "you",
        "it", "its", "as", "by", "from", "up", "out", "off", "over", "into"}


def norm(text: str) -> str:
    t = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode().lower()
    return re.sub(r"\s+", " ", t).strip()


def stem(w: str) -> str:
    for suf in ("ies", "ing", "ed", "es", "s", "ly"):
        if len(w) > len(suf) + 2 and w.endswith(suf):
            return w[: -len(suf)]
    return w


def base(w: str) -> str:
    """Same folding build_reading.py uses, so a tap on `procrastinating` or
    `bookshelves` reaches `procrastinate on` and `bookshelf`."""
    w = stem(w)
    while len(w) > 2 and w[-1] in "yi":
        w = w[:-1]
    if w.endswith("e"):
        w = w[:-1]
    if w.endswith("f"):
        w = w[:-1] + "v"
    return w


def is_stale() -> bool:
    """True when any day's yaml is newer than the built glossary."""
    if not OUT.exists():
        return True
    built = OUT.stat().st_mtime
    return any(f.stat().st_mtime > built for f in DATA.glob("day*.yaml"))


def main(force=True):
    if not force and not is_stale():
        return
    entries, seen = [], {}

    def audio_for(day, tier, cid=None, idx=None):
        """The course already speaks every word in neural TTS; the vault should
        use those files rather than the browser's own voice. `_m` is the primary
        voice the rest of the project uses."""
        stem_ = (f"chunk{cid}_m_chunk" if tier == "chunk"
                 else f"supp_{'basic' if tier == 'basic' else tier}_{idx:03d}_m")
        rel = f"day{day:02d}/audio/{stem_}.mp3"
        return rel if (ROOT / "output" / rel).exists() else None

    def add(en, zh, pos, day, tier, example=None, example_zh=None, audio=None):
        en, zh = (en or "").strip(), (zh or "").strip()
        if not en or not zh:
            return
        key = (norm(en), zh)
        if key in seen:                      # same word taught twice: keep the first day
            return
        seen[key] = True
        e = {"en": en, "zh": zh, "day": day, "tier": tier}
        if pos:
            e["pos"] = pos
        if example:
            e["ex"] = example
        if example_zh:
            e["exZh"] = example_zh
        if audio:
            e["au"] = audio
        entries.append(e)

    for yf in sorted(DATA.glob("day*.yaml")):
        if yf.stem.endswith("_examples"):
            continue
        d = yaml.safe_load(yf.read_text(encoding="utf-8"))
        day = d.get("day")
        if day is None:
            continue
        for c in d.get("chunks") or []:
            add(c.get("chunk"), c.get("meaning_zh"), None, day, "chunk",
                c.get("example"), c.get("example_zh"),
                audio_for(day, "chunk", cid=c.get("id")))
        supp = d.get("supplementary") or {}
        for tier in ("basic", "score_800", "score_900"):
            for i, w in enumerate(supp.get(tier) or []):
                add(w.get("en"), w.get("zh"), w.get("pos"), day, tier,
                    audio=audio_for(day, tier, idx=i))

    # word → entry indices. Every content word of a phrase is indexed, so a tap
    # on any one of them reaches the phrase.
    index = {}
    for i, e in enumerate(entries):
        words = {w for w in re.findall(r"[a-z']+", norm(e["en"])) if w not in STOP}
        for w in words | {stem(w) for w in words} | {base(w) for w in words}:
            if len(w) < 2:
                continue
            index.setdefault(w, [])
            if i not in index[w]:
                index[w].append(i)

    payload = {"entries": entries, "index": index}
    OUT.write_text(
        "/* Generated by build_glossary.py — every word the course teaches, with its Chinese.\n"
        "   Read by output/vault.html so a card can gloss the word, not just its sentence. */\n"
        "window.GLOSSARY = " + json.dumps(payload, ensure_ascii=False, separators=(",", ":")) + ";\n",
        encoding="utf-8")

    tiers = {}
    for e in entries:
        tiers[e["tier"]] = tiers.get(e["tier"], 0) + 1
    print(f"✓ Glossary rebuilt: {OUT}")
    with_audio = sum(1 for e in entries if e.get("au"))
    print(f"  {len(entries)} entries ({', '.join(f'{k} {v}' for k, v in sorted(tiers.items()))})"
          f" · {len(index)} indexed forms · {OUT.stat().st_size // 1024} KB")
    print(f"  {with_audio} with audio ({round(with_audio / max(1, len(entries)) * 100)}%)")


if __name__ == "__main__":
    # `--if-stale` is what other build steps call: cheap when nothing changed,
    # so every path that adds a day keeps the vault's glosses current.
    main(force="--if-stale" not in sys.argv)
