#!/usr/bin/env python3
"""Serve the practice pages and persist progress to real files.

    python3 scripts/serve.py          # then open http://localhost:8137/

Why this exists: the pages used to keep progress in localStorage only, which is
bound to the origin. Opening the same file as file:// and as http://localhost
gives you two separate, invisible sets of records — and clearing browsing data
wipes both. Progress now lands in output/progress/dayNN.json, which survives
cache clears, is readable outside the browser, and can go into git.

localStorage is still written on every answer, so the page keeps working if you
open it straight off disk; it just cannot sync until you come back through here.
"""
import http.server, json, os, re, socketserver, sys, datetime

PORT = int(sys.argv[1]) if len(sys.argv) > 1 else 8137
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WEB = os.path.join(ROOT, 'output')
PROG = os.path.join(WEB, 'progress')
os.makedirs(PROG, exist_ok=True)

SRS = os.path.join(PROG, 'srs.json')

def prog_path(day):
    return os.path.join(PROG, f'day{int(day):02d}.json')

def write_atomic(path, data):
    """A crash mid-save must not truncate history."""
    data['_saved'] = datetime.datetime.now().isoformat(timespec='seconds')
    tmp = path + '.tmp'
    with open(tmp, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    os.replace(tmp, path)
    return data['_saved']

class Handler(http.server.SimpleHTTPRequestHandler):
    def __init__(self, *a, **kw):
        super().__init__(*a, directory=WEB, **kw)

    def _json(self, obj, code=200):
        body = json.dumps(obj, ensure_ascii=False).encode()
        self.send_response(code)
        self.send_header('Content-Type', 'application/json; charset=utf-8')
        self.send_header('Content-Length', str(len(body)))
        self.send_header('Cache-Control', 'no-store')
        self.end_headers()
        self.wfile.write(body)

    def end_headers(self):
        # Pages are regenerated by build_trr.py; without this the browser keeps
        # serving the previous build and fixes appear not to have landed.
        if self.path.endswith('.html') or self.path.endswith('/'):
            self.send_header('Cache-Control', 'no-cache, must-revalidate')
        super().end_headers()

    def do_GET(self):
        m = re.match(r'^/api/progress/(\d+)$', self.path)
        if m:
            p = prog_path(m.group(1))
            if os.path.exists(p):
                return self._json(json.load(open(p, encoding='utf-8')))
            return self._json(None)
        if self.path == '/api/progress':
            out = {}
            for f in sorted(os.listdir(PROG)):
                # srs.json lives here too but is not a day record.
                if f.endswith('.json') and f.startswith('day'):
                    out[f[:-5]] = json.load(open(os.path.join(PROG, f), encoding='utf-8'))
            return self._json(out)
        if self.path == '/api/srs':
            if os.path.exists(SRS):
                return self._json(json.load(open(SRS, encoding='utf-8')))
            return self._json(None)
        return super().do_GET()

    def do_POST(self):
        n = int(self.headers.get('Content-Length', 0))

        if self.path == '/api/srs':
            try:
                data = json.loads(self.rfile.read(n) or b'{}')
            except Exception as e:
                return self._json({'error': str(e)}, 400)
            # The review schedule spans every day, so it cannot live in a
            # per-day file. One record, rewritten whole on each save.
            saved = write_atomic(SRS, data)
            return self._json({'ok': True, 'saved': saved,
                               'cards': len(data.get('cards', {})),
                               'answers': len(data.get('log', []))})

        m = re.match(r'^/api/progress/(\d+)$', self.path)
        if not m:
            return self._json({'error': 'not found'}, 404)
        try:
            data = json.loads(self.rfile.read(n) or b'{}')
        except Exception as e:
            return self._json({'error': str(e)}, 400)
        saved = write_atomic(prog_path(m.group(1)), data)
        return self._json({'ok': True, 'saved': saved,
                           'answers': len(data.get('log', []))})

    def log_message(self, fmt, *args):
        if '/api/' in (args[0] if args else ''):
            sys.stderr.write("  %s\n" % (fmt % args))

class Server(socketserver.ThreadingTCPServer):
    allow_reuse_address = True
    daemon_threads = True

if __name__ == '__main__':
    print(f'TOEIC practice → http://localhost:{PORT}/')
    print(f'progress files → {PROG}')
    days = sorted(d for d in os.listdir(WEB)
                  if re.fullmatch(r'day\d\d', d)
                  and os.path.exists(os.path.join(WEB, d, 'practice.html')))
    for d in days:
        print(f'    http://localhost:{PORT}/{d}/practice.html')
    print('Ctrl-C to stop.\n')
    with Server(('127.0.0.1', PORT), Handler) as s:
        try:
            s.serve_forever()
        except KeyboardInterrupt:
            print('\nstopped')
